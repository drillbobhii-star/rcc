import assert from 'node:assert/strict';
import { adminTools, executeAdminTool } from '../discord-admin/src/admin-tools.js';
const guildId = '123456789012345678';
const channelId = '223456789012345678';
const userId = '323456789012345678';
const channels = [{ id: channelId, type: 0, name: 'test', permission_overwrites: [
  { id: guildId, type: 0, allow: '1024', deny: '16' }
] }];
const calls = [];
let replies = {};
const api = async (path, options) => {
  calls.push({ path, options });
  const response = replies[path];
  if (response instanceof Error) throw response;
  return response;
};
const run = (name, args = {}, list = channels) => executeAdminTool(api, guildId, name, args, list);
assert.equal(adminTools.length, 5);
await assert.rejects(run('purge_messages', { channel_id: 'foreign', count: 10 }));
for (const count of [0, 101, 1.5, '5']) await assert.rejects(run('purge_messages', { channel_id: channelId, count }));
const snowflake = time => String((BigInt(time) - 1420070400000n) << 22n);
const recent = snowflake(Date.now() - 10000);
const old = snowflake(Date.now() - 15 * 86400000);
replies[`/channels/${channelId}/messages?limit=2`] = [{ id: recent }, { id: old }];
assert.match(await run('purge_messages', { channel_id: channelId, count: 2 }), /borrados: 1/);
assert.equal(calls.at(-1).options.method, 'DELETE');
replies[`/channels/${channelId}/messages?limit=2`] = [{ id: recent }, { id: snowflake(Date.now() - 20000) }];
await run('purge_messages', { channel_id: channelId, count: 2 });
assert.equal(calls.at(-1).options.body.messages.length, 2);
await run('lock_channel', { channel_id: channelId });
let overwrite = calls.at(-1).options.body;
assert.equal(BigInt(overwrite.allow) & 1024n, 1024n, 'Unrelated view permission survives');
assert.equal(BigInt(overwrite.deny) & (1n << 11n), 1n << 11n);
assert.equal(BigInt(overwrite.deny) & 16n, 16n);
channels[0].permission_overwrites[0] = { ...overwrite, id: guildId };
await run('unlock_channel', { channel_id: channelId });
overwrite = calls.at(-1).options.body;
assert.equal(BigInt(overwrite.deny) & (1n << 11n), 0n);
assert.equal(BigInt(overwrite.allow) & (1n << 11n), 1n << 11n);
replies[`/guilds/${guildId}?with_counts=true`] = { id: guildId, name: 'RCC', approximate_member_count: 42, premium_tier: 2 };
assert.equal((await run('server_info')).members, 42);
const missing = Object.assign(new Error('Not found'), { status: 404 });
replies[`/users/${userId}`] = { id: userId, username: 'member' };
replies[`/guilds/${guildId}/members/${userId}`] = { joined_at: '2026-01-01', roles: ['role'] };
replies[`/guilds/${guildId}/roles`] = [{ id: 'role', name: 'VIP' }];
replies[`/guilds/${guildId}/bans/${userId}`] = missing;
assert.equal((await run('user_info', { user_id: userId })).roles[0].name, 'VIP');
replies[`/guilds/${guildId}/members/${userId}`] = missing;
replies[`/guilds/${guildId}/bans/${userId}`] = { reason: 'test' };
assert.equal((await run('user_info', { user_id: userId })).banned, true);
replies[`/guilds/${guildId}/bans/${userId}`] = Object.assign(new Error('Forbidden'), { status: 403 });
await assert.rejects(run('user_info', { user_id: userId }), /Forbidden/, 'Missing permissions must not be reported as not banned');
await assert.rejects(run('user_info', { user_id: '../other' }));
console.log('Discord admin checks passed.');
